// Form-issued UUID is an idempotency key, not an authorization token.
// The server derives the account from its authenticated profile.
export function parseEconomicRequestId(value: FormDataEntryValue | null): string | null {
  if (typeof value !== "string") return null;
  return /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value)
    ? value.toLowerCase() : null;
}
